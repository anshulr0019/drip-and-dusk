// Writes ~480px WebP copies of the catalogue photos to dist/assets/sm/ and the dist/image-variants.mjs list the card code checks,
// so srcset is only ever emitted for a photo that really has a smaller copy. Originals are never touched.
// Usage: node scripts/image-variants.mjs   (needs the `cwebp` tool from libwebp; rerun after adding catalogue photos)
import {readdirSync,readFileSync,writeFileSync,mkdirSync,statSync,rmSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const dist=new URL('../dist/',import.meta.url),assets=new URL('assets/',dist),out=new URL('assets/sm/',dist);
export const WIDTH=480,QUALITY=78;
// Width straight from the file header, so the script needs no image library.
export function imageWidth(buf){
 if(buf.toString('latin1',0,4)==='RIFF'&&buf.toString('latin1',8,12)==='WEBP'){const kind=buf.toString('latin1',12,16);return kind==='VP8 '?buf.readUInt16LE(26)&0x3fff:kind==='VP8L'?(buf.readUInt32LE(21)&0x3fff)+1:kind==='VP8X'?buf.readUIntLE(24,3)+1:0}
 if(buf.readUInt32BE(0)===0x89504e47)return buf.readUInt32BE(16);
 if(buf[0]===0xff&&buf[1]===0xd8){let i=2;while(i+9<buf.length){if(buf[i]!==0xff){i++;continue}const m=buf[i+1];if(m>=0xc0&&m<=0xcf&&![0xc4,0xc8,0xcc].includes(m))return buf.readUInt16BE(i+7);i+=2+buf.readUInt16BE(i+2)}}
 return 0;
}
if(process.argv[1]&&import.meta.url===new URL('file://'+process.argv[1]).href){
 const cwebp=['cwebp','/opt/homebrew/bin/cwebp','/usr/local/bin/cwebp'].find(c=>{try{execFileSync(c,['-version'],{stdio:'ignore'});return true}catch{return false}});
 if(!cwebp)throw Error('cwebp is required: install libwebp (for example `brew install webp`).');
 rmSync(out,{recursive:true,force:true});mkdirSync(out,{recursive:true});
 const map={},names=new Set();
 // hero art keeps its own pipeline; the favicon is not a product photo.
 for(const file of readdirSync(assets).filter(f=>/\.(jpe?g|png|webp)$/i.test(f)&&!/^hero/.test(f)).sort()){
  const source=new URL(file,assets),width=imageWidth(readFileSync(source));
  if(!width||width<=WIDTH)continue;
  const stem=file.replace(/\.[^.]+$/,'');if(names.has(stem))throw Error('Two assets share the name '+stem+'; rename one before generating variants.');names.add(stem);
  const target=new URL(stem+'.webp',out);
  execFileSync(cwebp,['-quiet','-q',String(QUALITY),'-m','6','-resize',String(WIDTH),'0',fileURLToPath(source),'-o',fileURLToPath(target)]);
  // A copy that is not smaller would only add a request, so it is not listed.
  if(statSync(target).size>=statSync(source).size){rmSync(target);continue}
  map['assets/'+file]=['assets/sm/'+stem+'.webp',width];
 }
 const body=`// Generated by scripts/image-variants.mjs; do not edit by hand. Each entry: original photo -> [${WIDTH}px WebP copy, original width].
export const variantWidth=${WIDTH};
export const imageVariants={\n${Object.entries(map).map(([k,v])=>' '+JSON.stringify(k)+':'+JSON.stringify(v)).join(',\n')}\n};
// Only photos listed above get a srcset; owner uploads and anything else keep the single original.
export const imageSrcset=src=>Object.hasOwn(imageVariants,src)?\`\${imageVariants[src][0]} \${variantWidth}w, \${src} \${imageVariants[src][1]}w\`:'';
`;
 writeFileSync(new URL('image-variants.mjs',dist),body);
 console.log(Object.keys(map).length+' variants written to dist/assets/sm/ ('+(existsSync(out)?readdirSync(out).length:0)+' files)');
}
